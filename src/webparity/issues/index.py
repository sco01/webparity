"""``INDEX.md``: the table of filed issues (and posted comments), generated from the database only."""

from __future__ import annotations

from webparity.db import DB, now
from webparity.issues.common import data_dir, load_signatures


def _cell(value) -> str:
    return "" if value is None else str(value).replace("|", "\\|").replace("\n", " ")


def generate_index(config: dict, db: DB, write: bool = True) -> str:
    """Writes ``data_dir/INDEX.md`` (unless ``write`` is false) and returns its text."""
    repository = (config.get("github") or {}).get("repository") or "LadybirdBrowser/ladybird"
    base = f"https://github.com/{repository}/issues"
    issues = db.q("SELECT * FROM issues WHERE kind = 'issue' AND number IS NOT NULL ORDER BY number")
    drafts = db.q("SELECT * FROM issues WHERE number IS NULL AND kind = 'issue' AND state = 'draft' ORDER BY id")
    comments = db.q("SELECT * FROM issues WHERE kind = 'comment' ORDER BY filed, id")
    lines = [
        "<!-- Generated by webparity index; edits are overwritten. -->",
        "",
        f"# Issues in {repository}",
        "",
        f"{len(issues)} filed issues, {len(drafts)} drafts. Updated {now()}.",
        "",
        "| Issue | Title | State | Signatures | Filed | Closed | Verified |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in issues:
        sigs = ", ".join(f"`{s}`" for s in load_signatures(r["signatures"]))
        closed = _cell(r["closed"]) + (f" ({_cell(r['closed_by'])})" if r["closed_by"] else "")
        verified = _cell(r["verified_result"]) + (f" ({r['verified'][:10]})" if r["verified"] else "")
        lines.append(
            f"| [#{r['number']}]({base}/{r['number']}) | {_cell(r['title'])} | {_cell(r['state'])} | {_cell(sigs)}"
            f" | {_cell(r['filed'])} | {closed} | {verified} |"
        )
    if drafts:
        lines += ["", "## Drafts", "", "| Draft | Title | Signatures | Created |", "|---|---|---|---|"]
        for r in drafts:
            name = (r["draft"] or "").rsplit("/", 1)[-1]
            sigs = ", ".join(f"`{s}`" for s in load_signatures(r["signatures"]))
            created = (r["created"] or "")[:10]
            lines.append(f"| {_cell(name)} | {_cell(r['title'])} | {_cell(sigs)} | {created} |")
    if comments:
        lines += ["", "## Comments", "", "| On | Draft | Posted |", "|---|---|---|"]
        for r in comments:
            name = (r["draft"] or "").rsplit("/", 1)[-1]
            target = (r["note"] or "").removeprefix("comment on ")
            lines.append(f"| {_cell(target)} | {_cell(name)} | {_cell(r['filed'])} |")
    text = "\n".join(lines) + "\n"
    if write:
        path = data_dir(config) / "INDEX.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return text
